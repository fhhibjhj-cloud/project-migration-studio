CREATE TABLE public.users (
  id TEXT PRIMARY KEY, username TEXT UNIQUE NOT NULL, full_name TEXT NOT NULL,
  role TEXT DEFAULT 'user' CHECK (role IN ('user','admin')), balance_tomans BIGINT DEFAULT 0,
  phone TEXT, iban TEXT, card_number TEXT, is_banned BOOLEAN DEFAULT false, is_full_name_locked BOOLEAN DEFAULT false,
  password_hash TEXT, numeric_id BIGINT, data JSONB DEFAULT '{}'::jsonb,
  updated_at TIMESTAMPTZ DEFAULT now(), created_at TIMESTAMPTZ DEFAULT now());
CREATE TABLE public.messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id TEXT NOT NULL, user_name TEXT NOT NULL,
  sender TEXT NOT NULL CHECK (sender IN ('user','support')), text TEXT NOT NULL, ticket_id TEXT DEFAULT 'tkt_general',
  created_at TIMESTAMPTZ DEFAULT now());
CREATE TABLE public.predictions (
  id TEXT PRIMARY KEY, user_id TEXT NOT NULL, user_name TEXT NOT NULL, week_id TEXT NOT NULL,
  selections JSONB NOT NULL DEFAULT '{}'::jsonb, replacement_selections JSONB DEFAULT '{}'::jsonb,
  combinations_count INTEGER DEFAULT 1, total_cost_tomans BIGINT NOT NULL,
  status TEXT DEFAULT 'pending' CHECK (status IN ('pending','won','lost')), payout_tomans BIGINT DEFAULT 0,
  submitted_at TEXT NOT NULL, data JSONB DEFAULT '{}'::jsonb, created_at TIMESTAMPTZ DEFAULT now());
CREATE TABLE public.transactions (
  id TEXT PRIMARY KEY, user_id TEXT NOT NULL, user_numeric_id BIGINT, user_name TEXT NOT NULL,
  type TEXT NOT NULL CHECK (type IN ('deposit','withdraw','prediction_fee','prediction_win','refund')),
  amount_tomans BIGINT NOT NULL, approved_amount_tomans BIGINT, date TEXT NOT NULL,
  status TEXT DEFAULT 'pending' CHECK (status IN ('approved','pending','rejected')),
  iban TEXT, card_number TEXT, tracking_code TEXT NOT NULL, created_at TIMESTAMPTZ DEFAULT now());
CREATE TABLE public.live_chat (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_name TEXT NOT NULL, text TEXT NOT NULL, time TEXT,
